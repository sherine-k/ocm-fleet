import assert from "node:assert/strict";
import test from "node:test";
import { formatProjects, updateAgents } from "./generate-agents.mjs";

test("formats projects in name order, including optional agent instructions", () => {
  const nodes = {
    web: {
      data: {
        root: "client/web",
        metadata: {
          description: "Web.",
          additionalAgentInstruction: "Read web guidance.",
        },
      },
    },
    empty: { data: { root: "empty" } },
    server: {
      data: {
        root: "server",
        metadata: {
          description: "Server.",
          additionalAgentInstruction: ["First.", "Second."],
        },
      },
    },
  };

  assert.equal(
    formatProjects(nodes),
    [
      "- empty (empty) -",
      "- server (server) - Server. First., Second.",
      "- web (client/web) - Web. Read web guidance.",
    ].join("\n"),
  );
});

test("replaces only the generated section and is idempotent", () => {
  const original =
    "# Rules\n\nKeep this.\n\n## Nx Projects (autogenerated)\n\nOld list.\n\n## Next section\n\nKeep this too.\n";
  const expected =
    "# Rules\n\nKeep this.\n\n## Nx Projects (autogenerated)\n\nRegenerate: `npx nx run ocm-fleet:generate-agents`.\n\n- app (app) - App.\n\n## Next section\n\nKeep this too.\n";
  const nodes = {
    app: { data: { root: "app", metadata: { description: "App." } } },
  };

  assert.equal(updateAgents(original, nodes), expected);
  assert.equal(updateAgents(expected, nodes), expected);
});

test("updates a final section and adds a final newline", () => {
  assert.equal(
    updateAgents("# Rules\n\n## Nx Projects (autogenerated)\n\nOld list.", {}),
    "# Rules\n\n## Nx Projects (autogenerated)\n\nRegenerate: `npx nx run ocm-fleet:generate-agents`.\n",
  );
});

test("rejects missing or duplicate generated sections", () => {
  assert.throws(() => updateAgents("# Rules\n", {}), /exactly one/);
  assert.throws(
    () =>
      updateAgents(
        "## Nx Projects (autogenerated)\n\n## Nx Projects (autogenerated)\n",
        {},
      ),
    /exactly one/,
  );
});
